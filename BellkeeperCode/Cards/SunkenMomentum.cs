namespace Bellkeeper.BellkeeperCode.Cards;

/// <summary>
/// 沉蓄（U29，原名：沉钟蓄势）：造成 9 点伤害。当这张牌被【沉底】时，本场战斗其伤害增加 6 点。
/// </summary>
public class SunkenMomentum : BellkeeperCard
{
    public SunkenMomentum() : base(1, CardType.Attack, CardRarity.Uncommon, TargetType.AnyEnemy) { }

    protected override IEnumerable<DynamicVar> CanonicalVars => new DynamicVar[]
    {
        new DamageVar(10m, DamageProps.card),
        new IntVar("Bonus", 6m),
    };

    public void OnSunk()
    {
        DynamicVars.Damage.UpgradeValueBy(DynamicVars["Bonus"].BaseValue);
    }

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay play)
    {
        await CommonActions.CardAttack(this, play).Execute(choiceContext);
    }

    protected override void OnUpgrade()
    {
        DynamicVars.Damage.UpgradeValueBy(3m);
        DynamicVars["Bonus"].UpgradeValueBy(3m);
    }
}
