namespace Bellkeeper.BellkeeperCode.Cards;

/// <summary>
/// 铜槌猛击（C04）：造成 8 点伤害。获得 3 层【守御】。
/// </summary>
public class Brasstrike : BellkeeperCard
{
    public Brasstrike() : base(1, CardType.Attack, CardRarity.Common, TargetType.AnyEnemy) { }

    protected override IEnumerable<DynamicVar> CanonicalVars => new DynamicVar[]
    {
        new DamageVar(8m, DamageProps.card),
        new IntVar("Guard", 3m),
    };

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay play)
    {
        await CommonActions.CardAttack(this, play).Execute(choiceContext);
        await ChimeGrants.Grant<GuardPower>(choiceContext, this, DynamicVars["Guard"].IntValue);
    }

    protected override void OnUpgrade()
    {
        DynamicVars.Damage.UpgradeValueBy(3m);
        DynamicVars["Guard"].UpgradeValueBy(1m);
    }
}
