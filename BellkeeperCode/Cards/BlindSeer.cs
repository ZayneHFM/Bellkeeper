namespace Bellkeeper.BellkeeperCode.Cards;

/// <summary>
/// 盲眼先知（R22）：每回合你前 2 次从抽牌堆底抽牌时，获得 1 点能量。（升级后额外抽 1 张牌）
/// </summary>
public class BlindSeer : BellkeeperCard
{
    public BlindSeer() : base(1, CardType.Power, CardRarity.Rare, TargetType.Self) { }

    protected override IEnumerable<DynamicVar> CanonicalVars => Array.Empty<DynamicVar>();

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay play)
    {
        await PowerCmd.Apply<BlindSeerPower>(choiceContext, Owner.Creature, 1, Owner.Creature, this, false);
    }

    protected override void OnUpgrade()
    {
        EnergyCost.UpgradeBy(-1);
        AddKeyword(CardKeyword.Innate);
    }
}
